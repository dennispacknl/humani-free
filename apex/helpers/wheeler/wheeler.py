import os

# Define the directory containing the .php files
directory_path = './apex/wheel/'

# Define the output file
output_file = 'artisan.php'

# Get a list of all .php files in the directory
php_files = [f for f in os.listdir(directory_path) if f.endswith('.php')]

# Open the output file in write mode
with open(output_file, 'w') as file:
    # Write the opening PHP tag
    file.write("<?php\n")

    # Write the comment
    file.write("// Imports generated by Wheeler 1.0.5\n")

    # Write the include statements for each .php file with a semicolon
    for php_file in php_files:
        file.write(f"include 'apex/wheel/{php_file}';\n")

print(f"{output_file} file succesfully generated")
